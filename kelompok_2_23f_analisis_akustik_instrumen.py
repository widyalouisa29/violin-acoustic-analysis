# Compare harmonic-to-noise ratio (HNR)
# Dekomposisi sinyal menggunakan STFT untuk memisahkan komponen harmonik dan noise.
def harmonic_to_noise_ratio(y, sr):
    S, phase = librosa.magphase(librosa.stft(y))
    harmonic = librosa.decompose.hpss(S)[0]
    noise = S - harmonic
    hnr = np.sum(harmonic**2) / np.sum(noise**2)
    return 10 * np.log10(hnr)

hnr_tuned = harmonic_to_noise_ratio(y_tuned_normalized, sr_tuned)
