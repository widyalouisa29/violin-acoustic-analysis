#Filtering (Penyaringan Frekuensi)

from scipy.signal import butter, lfilter

# Fungsi untuk membuat dan menerapkan bandpass filter
def bandpass_filter(y, lowcut, highcut, sr, order=5):
    nyquist = 0.5 * sr  # Frekuensi Nyquist
    low = lowcut / nyquist
    high = highcut / nyquist
    b, a = butter(order, [low, high], btype='band')  # Bandpass filter
    y_filtered = lfilter(b, a, y)  # Aplikasikan filter pada sinyal
    return y_filtered

# Parameter filtering
lowcut = 196  # Frekuensi batas bawah (196 Hz = nada G3 biola)
highcut = 4000  # Frekuensi batas atas (4000 Hz untuk harmonik biola)
order = 5  # Order filter

